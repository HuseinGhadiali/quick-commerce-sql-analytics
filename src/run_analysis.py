"""Run every SQL file in sql/analysis against DuckDB, save CSVs and build results/RESULTS.md."""
from __future__ import annotations

import argparse
import re
import time
from pathlib import Path

import pandas as pd

from db import ROOT, build_database

ANALYSIS_DIR = ROOT / "sql" / "analysis"
RESULTS_DIR = ROOT / "results"


def question_title(sql: str) -> str:
    lines = [ln[2:].strip() for ln in sql.splitlines() if ln.startswith("--")]
    title = []
    for ln in lines:
        if ln.lower().startswith("skills:"):
            break
        title.append(re.sub(r"^\s+", "", ln))
    return " ".join(title)


def skills(sql: str) -> str:
    m = re.search(r"-- Skills:(.*)", sql)
    return m.group(1).strip() if m else ""


def run_all(con) -> dict[str, pd.DataFrame]:
    out = {}
    for f in sorted(ANALYSIS_DIR.glob("*.sql")):
        t0 = time.perf_counter()
        out[f.stem] = con.sql(f.read_text()).df()
        print(f"{f.stem:<32} {len(out[f.stem]):>4} rows  {time.perf_counter() - t0:5.2f}s")
    return out


def to_markdown(df: pd.DataFrame, max_rows: int = 25) -> str:
    df = df.head(max_rows).copy()
    for c in df.columns:
        if pd.api.types.is_datetime64_any_dtype(df[c]):
            df[c] = df[c].dt.date
    return df.to_markdown(index=False)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--raw", default=str(ROOT / "data" / "raw"))
    args = ap.parse_args()
    con = build_database(Path(args.raw))
    results = run_all(con)
    RESULTS_DIR.mkdir(exist_ok=True)
    parts = ["# Query results\n",
             "Auto-generated by `python src/run_analysis.py` from the synthetic dataset (seed 42). "
             "Each section shows the business question, the SQL techniques used and the output.\n"]
    for name, df in results.items():
        df.to_csv(RESULTS_DIR / f"{name}.csv", index=False)
        sql = (ANALYSIS_DIR / f"{name}.sql").read_text()
        parts.append(f"## {question_title(sql)}\n")
        parts.append(f"`sql/analysis/{name}.sql` · *{skills(sql)}*\n")
        parts.append(to_markdown(df) + "\n")
    (RESULTS_DIR / "RESULTS.md").write_text("\n".join(parts))
    print(f"\nWrote {len(results)} result sets to {RESULTS_DIR}")


if __name__ == "__main__":
    main()
